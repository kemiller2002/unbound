/// Pure rendering of the synthetic operating year.
module Unbound.Replay.SyntheticReport

open System
open System.Globalization
open Unbound.Replay.Json
open Unbound.Replay.Synthetic

let private date (year: int) (day: int) = DateOnly(year, 1, 1).AddDays(day).ToString("yyyy-MM-dd")

let private recipientJson (r: Domain.Recipient) =
    [ "recipient_name", JStr r.Name; "recipient_ein", opt JStr r.Ein; "recipient_state", opt JStr r.State ]

/// One JSON object per line (compact).
let private line (j: Json) = (render j).Replace("\n", "").Replace("  ", "")

let eventLine (year: int) (e: Event) : string =
    let common = [ "date", JStr(date year e.Day); "fund", JStr $"F{e.Fund:D6}"; "amount", JDec e.Amount ]

    match e.Txn with
    | Contribution(m, complex) -> JObj(common @ [ "type", JStr "contribution"; "method", JStr m; "complex", JBool complex ])
    | Grant(r, check, _) -> JObj(common @ [ "type", JStr "grant"; "payment", JStr(if check then "check" else "ach") ] @ recipientJson r)
    |> line

/// Work item as shown to a reviewer: no indication of whether it was injected.
let itemLine (year: int) (w: WorkItem) : string =
    JObj
        [ "date", JStr(date year w.Day)
          "kind", JStr w.Kind
          "reference", JStr w.Reference
          "fund", JStr $"F{w.Fund:D6}"
          "system_finding", JStr w.Detail ]
    |> line

let answerKeyLine (w: WorkItem) : string =
    JObj [ "reference", JStr w.Reference; "kind", JStr w.Kind; "injected", opt JStr w.Injected; "model_minutes", JNum w.ModelMinutes ]
    |> line

let summaryJson (c: Config) (inputs: (string * string) list) (s: Summary) : Json =
    JObj
        [ "seed", JStr(string c.Seed)
          "year", JInt(int64 c.Year)
          "config",
          JObj
              [ "funds", JInt(int64 c.Funds)
                "portfolio_share", JNum c.PortfolioShare
                "portfolio_size", JStr $"{fst c.PortfolioSize}-{snd c.PortfolioSize}"
                "grant_sigma", JNum c.GrantSigma
                "contribution_sigma", JNum c.ContribSigma
                "inject_per_1000_grants_per_category", JNum c.InjectPer1000
                "reuse_minutes", JNum c.ReuseMinutes
                "ops_minutes", JNum c.OpsMinutes ]
          "inputs", JArr(inputs |> List.map (fun (n, h) -> JObj [ "name", JStr n; "sha256", JStr h ]))
          "grants", JInt(int64 s.Grants)
          "contributions", JInt(int64 s.Contributions)
          "grant_dollars", JDec s.GrantDollars
          "contribution_dollars", JDec s.ContributionDollars
          "december_grant_share", JNum s.DecemberGrantShare
          "items_by_kind", JObj(s.ItemsByKind |> List.map (fun (k, n) -> k, JInt(int64 n)))
          "items_by_month", JObj(s.ItemsByMonth |> List.map (fun (m, n) -> string m, JInt(int64 n)))
          "peak_week", JObj [ "week", JInt(int64 (fst s.PeakWeek)); "items", JInt(int64 (snd s.PeakWeek)) ]
          "mean_week_items", JNum s.MeanWeek
          "exception_first_per_1000_grants", JNum s.ExceptionFirstPer1000Grants
          "exception_reuse_per_1000_grants", JNum s.ExceptionReusePer1000Grants
          "injected_cases", JInt(int64 s.Injected)
          "injected_outcome",
          JArr(s.InjectedOutcome |> List.map (fun (c, n, k) -> JObj [ "category", JStr c; "injected_grants", JInt(int64 n); "surfaced_to_a_person", JInt(int64 k) ]))
          "model_hours", JNum s.ModelHours ]

let private n0 (x: float) = x.ToString("#,0", CultureInfo.InvariantCulture)
let private f1 (x: float) = x.ToString("0.0", CultureInfo.InvariantCulture)

let toMarkdown (c: Config) (s: Summary) (sampleByKind: (string * int) list) : string =
    let row cells = "| " + String.concat " | " cells + " |"

    [ "# 16a Synthetic operating year — generated tables"
      ""
      $"Generated by `replay/` (`synth`), seed {c.Seed}, year {c.Year}, {n0 (float c.Funds)} funds. Do not edit by hand."
      "Purpose, method and the internal time study are in [report 16](16-SYNTHETIC-OPERATING-YEAR-AND-INTERNAL-TIME-STUDY.md)."
      ""
      "## 1. Volumes"
      ""
      row [ "Measure"; "Value" ]
      row [ "---"; "---" ]
      row [ "Grants"; n0 (float s.Grants) ]
      row [ "Contributions"; n0 (float s.Contributions) ]
      row [ "Grant dollars"; "$" + n0 (float s.GrantDollars) ]
      row [ "Contribution dollars"; "$" + n0 (float s.ContributionDollars) ]
      row [ "Share of grants in December"; (100.0 * s.DecemberGrantShare |> f1) + "%" ]
      row [ "First-time exceptions (incl. sanctions alerts) per 1,000 grants"; f1 s.ExceptionFirstPer1000Grants ]
      row [ "Reused determinations per 1,000 grants"; f1 s.ExceptionReusePer1000Grants ]
      row [ "Injected known-bad cases"; string s.Injected ]
      row [ "Work items per week: mean / peak (week)"; $"{f1 s.MeanWeek} / {snd s.PeakWeek} (week {fst s.PeakWeek + 1})" ]
      row [ "Modelled human hours (model minutes per item; to be replaced by the time study)"; n0 s.ModelHours ]
      ""
      "## 2. Work items by kind"
      ""
      row [ "Kind"; "Items"; "In time-study sample" ]
      row [ "---"; "---"; "---" ] ]
    @ (s.ItemsByKind
       |> List.map (fun (k, n) -> row [ k; n0 (float n); sampleByKind |> List.tryFind (fst >> (=) k) |> Option.map (snd >> string) |> Option.defaultValue "0" ]))
    @ [ ""; "## 3. Injected known-bad grants"; ""; row [ "Category"; "Injected"; "Surfaced to a person"; "Passed straight through" ]; row [ "---"; "---"; "---"; "---" ] ]
    @ (s.InjectedOutcome |> List.map (fun (c, n, k) -> row [ c; string n; string k; string (n - k) ]))
    @ [ ""; "## 4. Work items by month"; ""; row [ "Month"; "Items" ]; row [ "---"; "---" ] ]
    @ (s.ItemsByMonth |> List.map (fun (m, n) -> row [ CultureInfo.InvariantCulture.DateTimeFormat.GetAbbreviatedMonthName m; n0 (float n) ]))
    |> String.concat "\n"
    |> fun t -> t + "\n"

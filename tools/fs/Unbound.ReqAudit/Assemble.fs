/// The report files and their contents, in the order the Python wrote them.
let reports (d: Data) : (string * string) list = BODIES |> List.map (fun (file, body) -> file, doc (intro file) (body d))

let main (argv: string list) : int =
    let root = argv.[0]
    let mission = combine root (if argv.Length > 1 then argv.[1] else MISSION)
    let d = load (combine mission "data")
    // each report is generated and written before the next is computed, as the Python loop does
    for file, body in BODIES do
        writeText (combine mission file) (doc (intro file) (body d))
        Io.print $"wrote {file}"
    0

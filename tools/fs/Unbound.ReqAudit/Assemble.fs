let private intro (file: string) = INTROS |> List.find (fun (f, _, _) -> f = file) |> fun (_, t, i) -> t, i

let doc (title: string, introText: string) (body: string list) : string =
    $"# {title}\n\n{GEN}\n{strip introText}\n\n" + String.Join("\n\n", body |> List.filter (fun b -> strip b <> "")) + "\n"


let private passName (g: string) = match PASS.TryFind g with Some n -> n | None -> g

let private hashes = re "^(#+)"

let sectionsL (d: Data) (group: string) (names: string list option) (level: int) : string =
    let secs = d.S |> List.filter (fun sx -> pyEq (get "_group" sx) (J group) && (match names with None -> true | Some w -> List.contains (s "section" sx) w))
    let secs =
        match names with
        | Some w -> secs |> List.sortBy (fun sx -> List.findIndex ((=) (s "section" sx)) w)
        | None -> secs
    let demote (md: string) =
        Regex.Replace(md, hashes.Search.ToString(), MatchEvaluator(fun m -> String('#', min 6 (m.Groups.[1].Value.Length + level))), RegexOptions.Multiline)
    secs
    |> List.map (fun sx -> $"""{String('#', level)} {s "section" sx}

*Source pass: {passName group}.*

{demote (strip (s "markdown" sx))}""")
    |> String.concat "\n\n"

let sections d group names = sectionsL d group (Some names) 2

/// num(x): float(x) for int/float, else 0.0.
let num (x: Json) : float =
    match x with
    | JInt i -> float i
    | JFloat f -> f
    | JBool b -> (if b then 1.0 else 0.0)
    | _ -> 0.0

let private counterJ (xs: Json list list) = counter (xs |> List.map JArr)
let private c2 (c: (Json * int) list) (a: Json) (b: Json) = count c (JArr [ a; b ])
let private disp (r: Json) = at "disposition" r

let tDispositionMatrix (d: Data) =
    let c = counterJ (d.REG |> List.map (fun r -> [ at "_group" r; disp r ]))
    let rows = SLICES |> List.map (fun g -> J PASS.[g] :: (DISP |> List.map (fun k -> N(c2 c (J g) (J k)))) @ [ N(DISP |> List.sumBy (fun k -> c2 c (J g) (J k))) ])
    let tot = J "**Total**" :: (DISP |> List.map (fun k -> N(SLICES |> List.sumBy (fun g -> c2 c (J g) (J k))))) @ [ N d.REG.Length ]
    table ("Slice" :: DISP @ [ "Rows" ]) (rows @ [ tot ])

let private bigint (i: BigInteger) = JInt i

let tAggregates (d: Data) =
    let hw r = orElse (JObj []) (get "human_work" r)
    let cf r = orElse (JObj []) (get "customer_friction" r)
    let cb r = orElse (JObj []) (get "configuration_burden" r)
    let stated = Map.ofList [ "revB", 21125.0 ]
    let rows =
        SLICES
        |> List.map (fun g ->
            let rs = d.REG |> List.filter (fun r -> pyEq (at "_group" r) (J g))
            let acc f = rs |> List.fold (fun (a: float) r -> a + f r) 0.0
            if rs.IsEmpty then [ J PASS.[g]; N 0; N 0; bigint (PyFloat.roundInt (stated.TryFind g |> Option.defaultValue 0.0)); N 0; N 0 ]
            else
                let hours = acc (fun r -> num (get "hours_per_10k_accounts_per_year" (hw r)))
                let avoid = acc (fun r -> num (get "avoidable_hours_per_10k_accounts_per_year" (hw r)))
                let inter = acc (fun r -> num (get "interactions_per_account_per_year" (cf r)))
                let settings = acc (fun r -> num (get "settings" (cb r)))
                [ J PASS.[g]; N rs.Length; bigint (PyFloat.roundInt hours)
                  bigint (PyFloat.roundInt (if avoid <> 0.0 then avoid else stated.TryFind g |> Option.defaultValue 0.0))
                  JFloat(PyFloat.roundTo 2 inter); bigint (PyFloat.roundInt settings) ])
    let intAt i (r: Json list) = match r.[i] with JInt v -> v | _ -> BigInteger.Zero
    let sumInt i = rows |> List.fold (fun (a: BigInteger) r -> a + intAt i r) BigInteger.Zero
    let interTotal =
        let floats = rows |> List.choose (fun r -> match r.[4] with JFloat x -> Some x | _ -> None)
        if floats.IsEmpty then JInt BigInteger.Zero else JFloat(PyFloat.roundTo 2 (PySum.sum floats))
    let tot = [ J "**Total**"; bigint (sumInt 1); bigint (sumInt 2); bigint (sumInt 3); interTotal; bigint (sumInt 5) ]
    table [ "Slice"; "Rows"; "Human hours per 10k accounts/yr as written [A/D]"; "Avoidable [A/D]"; "Interactions per account/yr implied [A]"; "Settings [A]" ] (rows @ [ tot ])


/// Render owner ratification packets (report 11) (port of tools/reqaudit/render_ratification_packets.py).
module Unbound.Convergence.RenderRatificationPackets

open Unbound.Py.PyJson
open Unbound.Convergence.PyCompat
module QL = Unbound.Convergence.QuestionsLib

let MISSION = "requirements/convergence/2026-11-24-master"

let DOMAIN_NAMES =
    Map.ofList
        [ "FIN", "Accounting and financial reporting"; "PAY", "Banking and payments"; "GRT", "Grants, eligibility and sanctions"
          "LEG", "Regulatory perimeter"; "ENT", "Accounts, succession and exit"; "ADM", "Service operations"
          "PLT", "Platform, identity, communications and records"; "TEN", "Tenancy"; "GOV", "Governance and assurance"
          "INV", "Investments"; "ECO", "Economics and commercial"; "EXP", "Experience"; "AIO", "AI authority" ]

let cell = RenderDecisionRegister.cell
let private domainName (d: string) = DOMAIN_NAMES.TryFind d |> Option.defaultValue d

let main (io: Io.Console) (argv: string list) : int =
    let root = argv.[1]
    let states = QL.fold (QL.loadEvents root)
    let clauses = Io.readJsonl (Io.path root (MISSION + "/data/convergence-clauses.jsonl"))
    let baseRows = Io.readJsonl (Io.path root "requirements/baseline/baseline.jsonl") |> List.map (fun r -> item "id" r, r) |> Map.ofList
    let domainOfQ =
        clauses
        |> List.fold
            (fun (m: Map<string, string>) c ->
                strs (item "resolves" c) |> List.fold (fun (m: Map<string, string>) q -> if m.ContainsKey q then m else m.Add(q, itemStr "domain" c)) m)
            Map.empty
    let pending = QL.stateItems states |> List.filter (fun (_, st) -> get "approval_status" st = Some(JStr "agent-recommended"))
    let unratified =
        clauses
        |> List.filter (fun c ->
            let basis = baseRows.TryFind(item "id" c) |> Option.defaultValue (JObj []) |> getStr "approval_basis"
            startsWith "agent-recommended" basis || startsWith "mission-adopted" basis)
    let byDomain =
        pending
        |> sortByStrs (fun (q, _) -> [ q ])
        |> List.fold
            (fun (acc: (string * (string * Json) list) list) (q, st) ->
                let d = domainOfQ.TryFind q |> Option.defaultValue "GOV"
                if acc |> List.exists (fst >> (=) d) then acc |> List.map (fun (k, v) -> if k = d then k, v @ [ q, st ] else k, v)
                else acc @ [ d, [ q, st ] ])
            []
        |> sortByStrs (fun (d, _) -> [ d ])
    let resolvesAny (c: Json) (rows: (string * Json) list) = rows |> List.exists (fun (q, _) -> List.contains q (strs (item "resolves" c)))
    let domainCounts = unratified |> List.map (itemStr "domain") |> counter |> List.sortWith (fun (a, _) (b, _) -> cmpStr a b)
    let summary =
        "## Summary\n\n| Packet | Domain | Questions to ratify | Clauses affected |\n|---|---|---|---|\n"
        + (byDomain
           |> List.map (fun (d, rows) ->
               let n = clauses |> List.filter (fun c -> itemStr "domain" c = d && resolvesAny c rows) |> List.map (itemStr "id") |> List.distinct |> List.length
               $"| P-{d} | {domainName d} | {rows.Length} | {n} |")
           |> String.concat "\n")
        + $"\n| **Total** | | **{pending.Length}** | |"
    let packets =
        byDomain
        |> List.map (fun (d, rows) ->
            let cls = clauses |> List.filter (fun c -> itemStr "domain" c = d && (resolvesAny c rows || List.contains c unratified))
            let orDash (x: string) = if x = "" then "—" else x
            $"## Packet P-{d} — {domainName d}\n\n**Clauses:** "
            + (cls |> List.map (fun c -> $"""{itemStr "id" c} {cell None (get "title" c)}""") |> String.concat "; ")
            + "\n\n| Question | Disposition | Confidence | Recommended answer | Replaced earlier answer | External gate |\n|---|---|---|---|---|---|\n"
            + (rows
               |> List.map (fun (q, st) ->
                   $"""| {q} | {getStr "disposition" st} | {getStr "confidence" st} | {cell (Some 420) (get "answer" st)} | """
                   + $"""{cell (Some 160) (get "superseded_answer" st) |> orDash} | {cell (Some 160) (Some(getOr "external_authorization_required" JNull st |> orElse (getOr "activation_gate" JNull st))) |> orDash} |""")
               |> String.concat "\n"))
    let advOnly = unratified |> List.filter (fun c -> not (truthy (item "resolves" c)))
    let parts =
        [ "# 11 — Owner ratification packets"
          "Generated by `tools/reqaudit/render_ratification_packets.py`; do not edit by hand."
          "**Why this exists.** The mission recommended that the owner ratify the agent-recommended resolutions *by domain* "
          + "rather than as a whole. When asked to 'do what you recommend', the five specific decisions OD-M-01..05 were recorded "
          + "(data/owner-decisions.jsonl) but blanket ratification of the remaining resolutions was deliberately **not** recorded "
          + "on the owner's behalf: approval should follow an actual review. Each packet below lists what the owner is approving."
          "**How to ratify.** Tell the agent, per packet: *ratify*, *ratify except <IDs>*, or *reject <IDs> with reason*. The agent "
          + "then appends one `approved` (or `reopened`) event per question to `requirements/questions/resolution-events.jsonl`, "
          + "re-runs `tools/reqaudit/adopt_convergence.py`, and the baseline index shows the clause as owner-approved. Ratification "
          + "approves product direction only; it is not a legal, accounting, bank or auditor approval, and activation gates remain."
          summary
          $"Clauses whose approval basis is still agent-recommended or mission-adopted: {unratified.Length} "
          + "("
          + (domainCounts |> List.map (fun (d, n) -> $"{d} {n}") |> String.concat ", ")
          + ")." ]
        @ packets
        @ [ "## Packet P-ADV — clauses adopted from the adversarial review (no register question)\n\n"
            + (advOnly |> List.map (fun c -> $"""- **{itemStr "id" c}** {cell None (get "title" c)}: {cell (Some 500) (get "statement" c)}""") |> String.concat "\n") ]
    Io.writeText (Io.path root (MISSION + "/11-OWNER-RATIFICATION-PACKETS.md")) (String.concat "\n\n" parts + "\n")
    io.Out($"{pending.Length} questions; {byDomain.Length} packets; {unratified.Length} unratified clauses; {advOnly.Length} adversarial-only\n")
    0

#!/usr/bin/env python3
"""Render the master-mission decision register and rejected-alternatives report from the resolution log (pure render).

Output: requirements/convergence/2026-11-24-master/09-DECISION-REGISTER-AND-REJECTED-ALTERNATIVES.md
Usage: python3 -I -B tools/reqaudit/render_decision_register.py <repo-root>
"""
import csv
import io
import json
import sys
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import questions_lib as ql  # noqa: E402

MISSION = Path("requirements/convergence/2026-11-24-master")
OWNER_DECISIONS = (("SPD-ADV-001", "No team exercises reserved authority for more than one sponsor; each sponsor decides with its own people.", "Product owner, 2026-11-24"),
                   ("SPD-ADV-004", "Unbound is a software platform only; customers employ everyone who does human work; hooks kept for staffed services. AMENDED by OD-M-08: software first, Unbound-operated administration as a planned second offer.", "Product owner, 2026-11-24"),
                   ("SPD-ECN-003", "Platform pricing includes a per-sponsor component in addition to per-account fees (decided-provisional).", "Product owner, 2026-11-24"))


def cell(t, n=None):
    s = " ".join(str(t or "").split()).replace("|", "\\|")
    return s if n is None or len(s) <= n else s[: n - 1] + "…"


def table(h, rows):
    return "\n".join(["| " + " | ".join(h) + " |", "|" + "---|" * len(h)] + ["| " + " | ".join(r) + " |" for r in rows])


def superseded_answers(state):
    """Every answer text this question held before its current one (rejected or replaced directions)."""
    return tuple(dict.fromkeys(a for a in (state.get("superseded_answer"),) if a and a != state.get("answer")))


def main(argv):
    root = Path(argv[1])
    states = ql.fold(ql.load_events(root))
    reg = {r["question_id"]: r for r in ql.load_csv(root / "requirements/open-questions.csv")}
    dossiers = {json.loads(l)["question_id"]: json.loads(l) for l in (root / MISSION / "data/dossiers.jsonl").read_text().splitlines() if l.strip()}
    clauses = [json.loads(l) for l in (root / MISSION / "data/convergence-clauses.jsonl").read_text().splitlines() if l.strip()]
    od = root / MISSION / "data/owner-decisions.jsonl"
    owner_decisions = [json.loads(l) for l in od.read_text().splitlines() if l.strip()] if od.exists() else []
    rows = [(q, reg[q]["kind"], cell(reg[q]["question"].removeprefix("Confirm provisional decision: "), 140), cell(s.get("answer"), 260),
             s.get("disposition", ""), s.get("approval_status", ""), ", ".join(s.get("applied_to", ()) or ()) or (("dup of " + s.get("canonical_id", "")) if s.get("canonical_id") else ""),
             cell(s.get("external_authorization_required") or s.get("activation_gate"), 160))
            for q, s in sorted(states.items())]
    rejected = [(q, cell(a, 220), cell(states[q].get("answer"), 200)) for q in sorted(states) for a in superseded_answers(states[q])]
    competing = [(q, cell(d.get("competing_interpretation"), 260), cell(d.get("alternative_design"), 260)) for q, d in sorted(dossiers.items())
                 if d.get("competing_interpretation") or d.get("alternative_design")]
    prior_rejected = sum(1 for p in ("requirements/discovery/2026-11-23-cross-industry/data/rejected.jsonl",
                                     "requirements/discovery/2026-11-24-simplification-economics/data/rejected.jsonl")
                         for l in (root / p).read_text().splitlines() if l.strip())
    gates = [(q, s.get("disposition"), cell(s.get("external_authorization_required") or s.get("activation_gate"), 300))
             for q, s in sorted(states.items()) if s.get("disposition") == "external-authorization-required" and s.get("resolution_status") == "resolved"]
    activation = [(c["id"], c["release_scope"], cell(c["activation_gate"], 300)) for c in clauses if c["activation_gate"]]
    text = "\n\n".join([
        "# 09 — Decision register, rejected alternatives and activation gates",
        "Generated by `tools/reqaudit/render_decision_register.py` from the resolution log, dossiers and convergence clauses; do not edit by hand.",
        "## 1. Owner decisions outside the question register\n\n" + table(("Decision", "Decision text", "Authority"), [(a, b, c) for a, b, c in OWNER_DECISIONS]
            + [(d["id"], cell(d["decision"], 600), cell(d["decided_by"], 160)) for d in owner_decisions]),
        "## 2. Summary\n\n" + table(("Measure", "Count"), [(f"{k[0]} / {k[1]}", str(v)) for k, v in sorted(Counter((s.get('resolution_status'), s.get('approval_status')) for s in states.values()).items())]
                                     + [("disposition: " + k, str(v)) for k, v in sorted(Counter(s.get('disposition', '') for s in states.values()).items())]),
        f"## 3. Regulatory and external activation gates ({len(gates)} questions; {len(activation)} clauses)\n\n"
        "These are the only places where an external party's act is required. Each names the authorization; none is a generic consultation.\n\n"
        + table(("Question", "Disposition", "Exact authorization required"), gates) + "\n\n" + table(("Clause", "Release scope", "Activation gate"), activation),
        f"## 4. Decision register ({len(rows)} questions)\n\n" + table(("ID", "Kind", "Question", "Decision", "Disposition", "Approval", "Incorporated as", "Gate"), rows),
        f"## 5. Rejected or replaced directions ({len(rejected)})\n\nAnswers that an earlier review proposed and a later review or evidence replaced.\n\n"
        + table(("Question", "Rejected or replaced direction", "Current decision"), rejected),
        f"## 6. Competing interpretations and alternative designs considered ({len(competing)})\n\n"
        + table(("Question", "Competing interpretation (not adopted)", "Alternative design (recorded for reconsideration)"), competing),
        f"## 7. Earlier missions' rejected approaches\n\n{prior_rejected} rejected approaches are recorded in "
        "`requirements/discovery/2026-11-23-cross-industry/data/rejected.jsonl` and `requirements/discovery/2026-11-24-simplification-economics/data/rejected.jsonl` "
        "(report 19 of the simplification mission). None was reinstated by this mission.",
    ]) + "\n"
    (root / MISSION / "09-DECISION-REGISTER-AND-REJECTED-ALTERNATIVES.md").write_text(text, encoding="utf-8")
    print(len(rows), "decisions;", len(rejected), "rejected;", len(gates), "gates")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))

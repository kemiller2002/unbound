#!/usr/bin/env python3
"""Render owner ratification packets (report 11): agent-recommended resolutions grouped by the domain of the clause
that incorporates them, so the owner can approve, amend or reject one domain at a time (pure render).

Recording a ratification is a separate, explicit step: append an 'approved' event per question with
approved_by naming the owner and the packet, only after the owner has reviewed that packet.

Usage: python3 -I -B tools/reqaudit/render_ratification_packets.py <repo-root>
"""
import json
import sys
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import questions_lib as ql  # noqa: E402

MISSION = Path("requirements/convergence/2026-11-24-master")
DOMAIN_NAMES = {"FIN": "Accounting and financial reporting", "PAY": "Banking and payments", "GRT": "Grants, eligibility and sanctions",
                "LEG": "Regulatory perimeter", "ENT": "Accounts, succession and exit", "ADM": "Service operations",
                "PLT": "Platform, identity, communications and records", "TEN": "Tenancy", "GOV": "Governance and assurance",
                "INV": "Investments", "ECO": "Economics and commercial", "EXP": "Experience", "AIO": "AI authority"}


def cell(t, n=None):
    s = " ".join(str(t or "").split()).replace("|", "\\|")
    return s if n is None or len(s) <= n else s[: n - 1] + "…"


def main(argv):
    root = Path(argv[1])
    states = ql.fold(ql.load_events(root))
    clauses = [json.loads(l) for l in (root / MISSION / "data/convergence-clauses.jsonl").read_text().splitlines() if l.strip()]
    base = {json.loads(l)["id"]: json.loads(l) for l in (root / "requirements/baseline/baseline.jsonl").read_text().splitlines() if l.strip()}
    domain_of_q = {}
    for c in clauses:
        for q in c["resolves"]:
            domain_of_q.setdefault(q, c["domain"])
    pending = {q: s for q, s in states.items() if s.get("approval_status") == "agent-recommended"}
    unratified = [c for c in clauses if base.get(c["id"], {}).get("approval_basis", "").startswith(("agent-recommended", "mission-adopted"))]
    by_domain = {}
    for q, s in sorted(pending.items()):
        by_domain.setdefault(domain_of_q.get(q, "GOV"), []).append((q, s))
    parts = ["# 11 — Owner ratification packets",
             "Generated by `tools/reqaudit/render_ratification_packets.py`; do not edit by hand.",
             "**Why this exists.** The mission recommended that the owner ratify the agent-recommended resolutions *by domain* "
             "rather than as a whole. When asked to 'do what you recommend', the five specific decisions OD-M-01..05 were recorded "
             "(data/owner-decisions.jsonl) but blanket ratification of the remaining resolutions was deliberately **not** recorded "
             "on the owner's behalf: approval should follow an actual review. Each packet below lists what the owner is approving.",
             "**How to ratify.** Tell the agent, per packet: *ratify*, *ratify except <IDs>*, or *reject <IDs> with reason*. The agent "
             "then appends one `approved` (or `reopened`) event per question to `requirements/questions/resolution-events.jsonl`, "
             "re-runs `tools/reqaudit/adopt_convergence.py`, and the baseline index shows the clause as owner-approved. Ratification "
             "approves product direction only; it is not a legal, accounting, bank or auditor approval, and activation gates remain.",
             "## Summary\n\n| Packet | Domain | Questions to ratify | Clauses affected |\n|---|---|---|---|\n" + "\n".join(
                 f"| P-{d} | {DOMAIN_NAMES.get(d, d)} | {len(rows)} | {len({c['id'] for c in clauses if c['domain'] == d and any(q in c['resolves'] for q, _ in rows)})} |"
                 for d, rows in sorted(by_domain.items())) + f"\n| **Total** | | **{len(pending)}** | |",
             f"Clauses whose approval basis is still agent-recommended or mission-adopted: {len(unratified)} "
             f"({', '.join(sorted(Counter(c['domain'] for c in unratified).elements()) and '')}{', '.join(f'{d} {n}' for d, n in sorted(Counter(c['domain'] for c in unratified).items()))})."]
    for d, rows in sorted(by_domain.items()):
        cls = [c for c in clauses if c["domain"] == d and (any(q in c["resolves"] for q, _ in rows) or c in unratified)]
        parts.append(f"## Packet P-{d} — {DOMAIN_NAMES.get(d, d)}\n\n**Clauses:** " + "; ".join(f"{c['id']} {cell(c['title'])}" for c in cls)
                     + "\n\n| Question | Disposition | Confidence | Recommended answer | Replaced earlier answer | External gate |\n|---|---|---|---|---|---|\n"
                     + "\n".join(f"| {q} | {s.get('disposition', '')} | {s.get('confidence', '')} | {cell(s.get('answer'), 420)} | "
                                 f"{cell(s.get('superseded_answer'), 160) or '—'} | {cell(s.get('external_authorization_required') or s.get('activation_gate'), 160) or '—'} |"
                                 for q, s in rows))
    adv_only = [c for c in unratified if not c["resolves"]]
    parts.append("## Packet P-ADV — clauses adopted from the adversarial review (no register question)\n\n"
                 + "\n".join(f"- **{c['id']}** {cell(c['title'])}: {cell(c['statement'], 500)}" for c in adv_only))
    (root / MISSION / "11-OWNER-RATIFICATION-PACKETS.md").write_text("\n\n".join(parts) + "\n", encoding="utf-8")
    print(len(pending), "questions;", len(by_domain), "packets;", len(unratified), "unratified clauses;", len(adv_only), "adversarial-only")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))

"""Assemble the numbered reports of the simplification mission from its data files.

Every report 01-22 is generated: narrative sections come from data/report-sections.jsonl (written by the role-separated
passes; field _group names the pass) and tables come from the record files. Reports 00, 23, README and LEDGER are
hand-written. Re-run after any data change; never edit the generated reports by hand.

Usage: python3 -I -B tools/reqaudit/assemble_simplification.py <repo-root> [mission-dir]
"""
